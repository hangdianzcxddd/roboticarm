def main() -> None:
    for index, command in enumerate(COMMANDS, start=1):
        print(f"\n[{index}/{len(COMMANDS)}] Running: {' '.join(command)}", flush=True)
        subprocess.run(command, check=True)
        if index < len(COMMANDS):
            delay_s = FINAL_RESET_DELAY_S if index == len(COMMANDS) - 1 else DELAY_S
            time.sleep(delay_s)


if __name__ == "__main__":
    main()
